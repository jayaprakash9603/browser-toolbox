#!/usr/bin/env node
/**
 * Writes the `[data-palette]` blocks in src/styles/tokens.css and the toolbar icon sets in
 * public/icons/themes/<id>/ from src/shared/lib/theme/palettes.ts.
 *
 *   node scripts/generate-palettes.mjs           CSS for every palette, icons only where missing
 *   node scripts/generate-palettes.mjs --icons   also redraw icons that already exist
 */
import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

import { LOGO_DARK_BASE, PALETTES } from '../src/shared/lib/theme/palettes.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const tokensPath = join(root, 'src/styles/tokens.css')
const START = '/* palettes:start (generated by scripts/generate-palettes.mjs) */'
const END = '/* palettes:end */'
const ICON_SIZES = [16, 32, 48, 128]
const redrawIcons = process.argv.includes('--icons')

const hex = (value) => value.toLowerCase()

function paletteCss(palette) {
  const [primary, secondary, accent] = palette.swatches.map(hex)
  const { hero, tiles, primaryForeground } = palette.light
  const light = [
    ['primary', primary],
    ['primary-foreground', primaryForeground],
    ['secondary-brand', secondary],
    ['accent-brand', accent],
    ['ring', primary],
    ['hero-from', hero[0]],
    ['hero-via', hero[1]],
    ['hero-to', hero[2]],
    ...tiles.map((color, i) => [`tile-${i + 1}`, color]),
  ]
  const dark = [
    ['primary', palette.dark.primary],
    ['primary-foreground', palette.dark.primaryForeground],
    ['ring', palette.dark.primary],
  ]
  const block = (selector, entries) =>
    `${selector} {\n${entries.map(([name, value]) => `  --${name}: ${hex(value)};`).join('\n')}\n}\n`
  return `${block(`[data-palette='${palette.id}']`, light)}\n${block(`.dark[data-palette='${palette.id}']`, dark)}`
}

async function writeCss() {
  const css = await readFile(tokensPath, 'utf8')
  const eol = css.includes('\r\n') ? '\r\n' : '\n'
  const normalized = css.replace(/\r\n/g, '\n')
  let head = normalized
  let tail = ''
  const start = normalized.indexOf(START)
  if (start >= 0) {
    head = normalized.slice(0, start)
    tail = normalized.slice(normalized.indexOf(END, start) + END.length)
  } else {
    const legacy = normalized.indexOf(`[data-palette='`)
    if (legacy < 0) throw new Error('tokens.css: no palette blocks or markers found')
    head = normalized.slice(0, legacy)
  }
  const body = PALETTES.map(paletteCss).join('\n')
  const next = `${head.trimEnd()}\n\n${START}\n\n${body}\n${END}${tail.trimEnd() ? tail : '\n'}`
  await writeFile(tokensPath, next.replace(/\n/g, eol))
  console.log(`tokens.css: ${PALETTES.length} palettes`)
}

/** Same mark as src/shared/components/BrandLogo.tsx. */
function logoSvg(palette, dark, size) {
  const stops = dark ? [palette.logoDark.from, palette.logoDark.to] : [palette.logo.from, palette.logo.via, palette.logo.to]
  const gradient = stops.map((color, i) => `<stop offset="${i / (stops.length - 1)}" stop-color="${color}"/>`).join('')
  const ink = dark ? 'url(#g)' : '#ffffff'
  const accent = dark ? palette.logoDark.accent : palette.logo.accent
  const base = dark
    ? `<rect x="3" y="3" width="58" height="58" rx="11" fill="${LOGO_DARK_BASE}"/><rect x="3" y="3" width="58" height="58" rx="11" fill="url(#g)" fill-opacity="0.14"/>`
    : `<rect x="3" y="3" width="58" height="58" rx="11" fill="url(#g)"/>`
  const dots = dark ? LOGO_DARK_BASE : 'url(#g)'
  const edge = dark
    ? ''
    : `<rect x="0.25" y="0.25" width="63.5" height="63.5" rx="13.75" stroke="${palette.logo.from}" stroke-opacity="0.35" stroke-width="0.5"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${size}" height="${size}" fill="none">
<defs><linearGradient id="g" x1="0" y1="0" x2="64" y2="64" gradientUnits="userSpaceOnUse">${gradient}</linearGradient>
<clipPath id="w"><rect x="3" y="3" width="58" height="58" rx="11"/></clipPath></defs>
${base}
<g stroke="${ink}" stroke-linejoin="round"><path clip-path="url(#w)" stroke-width="12" d="M3 12H38"/>
<rect x="3" y="3" width="58" height="58" rx="11" stroke-width="6"/>
<path stroke-width="6.5" stroke-linecap="round" d="M35.5 30.5 44 22v39"/></g>
<g fill="${dots}"><circle cx="12.5" cy="12" r="2.4"/><circle cx="19.5" cy="12" r="2.4"/><circle cx="26.5" cy="12" r="2.4"/></g>
<circle cx="51" cy="12.5" r="3.2" fill="${accent}"/>${edge}</svg>`
}

async function writeIcons() {
  let drawn = 0
  for (const palette of PALETTES) {
    for (const dark of [false, true]) {
      const dir = join(root, 'public/icons/themes', palette.id, dark ? 'dark' : '')
      if (!redrawIcons && existsSync(join(dir, 'icon128.png'))) continue
      await mkdir(dir, { recursive: true })
      for (const size of ICON_SIZES) {
        // Rendered at 4x and downsampled so thin strokes stay crisp at 16 px.
        const png = await sharp(Buffer.from(logoSvg(palette, dark, size * 4)))
          .resize(size, size, { kernel: 'lanczos3' })
          .png({ compressionLevel: 9 })
          .toBuffer()
        await writeFile(join(dir, `icon${size}.png`), png)
      }
      drawn++
    }
  }
  console.log(`icons: ${drawn} sets drawn`)
}

await writeCss()
await writeIcons()

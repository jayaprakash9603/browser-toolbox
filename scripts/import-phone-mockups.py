def resolve_source_dir(zip_path: Path | None, source_dir: Path | None) -> Path:
    if source_dir and source_dir.is_dir():
        return source_dir
    if zip_path and zip_path.is_file():
        extract_to = ROOT / "tmp-mockups-extract"
        extract_to.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(zip_path) as zf:
            zf.extractall(extract_to)
        return extract_to
    default = ROOT / "tmp-mockups-extract"
    if default.is_dir():
        return default
    raise SystemExit("Pass --source-dir or --zip with mockup files")


def punch_screen_hole(image: Image.Image, *, bright_threshold: int = 215) -> Image.Image:
    """Turn the empty screen fill into transparency (bundle PNGs ship opaque whites)."""
    rgba = image.convert("RGBA")
    w, h = rgba.size
    px = rgba.load()

    def is_screen(r: int, g: int, b: int, a: int) -> bool:
        if a < 10:
            return True
        mean = (r + g + b) / 3
        if mean > bright_threshold and max(r, g, b) - min(r, g, b) < 28:
            return True
        return False

    seeds = [(w // 2, y) for y in range(h // 5, 4 * h // 5, max(1, h // 80))]
    stack = [s for s in seeds if is_screen(*px[s])]
    seen: set[tuple[int, int]] = set()
    while stack:
        x, y = stack.pop()
        if (x, y) in seen or x < 0 or y < 0 or x >= w or y >= h:
            continue
        seen.add((x, y))
        r, g, b, a = px[x, y]
        if not is_screen(r, g, b, a):
            continue
        px[x, y] = (r, g, b, 0)
        stack.extend([(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)])
    return rgba


def to_output_webp(source: Path, dest: Path) -> None:
    punched = punch_screen_hole(Image.open(source))
    w, h = punched.size
    if w != OUTPUT_WIDTH:
        nh = max(1, round(h * OUTPUT_WIDTH / w))
        punched = punched.resize((OUTPUT_WIDTH, nh), Image.LANCZOS)
    punched.save(dest, format="WEBP", quality=92, method=6)


def emit_generated_ts(frames: dict[str, dict]) -> None:
    lines = [
        "/** Generated by scripts/import-phone-mockups.py — do not edit by hand. */",
        "",
        "export const MOCKUP_FRAMES: Record<string, { left: number; top: number; right: number; bottom: number }> = {",
    ]
    for name, data in sorted(frames.items()):
        lines.append(
            f"  {json.dumps(name)}: "
            f"{{ left: {data['left']}, top: {data['top']}, "
            f"right: {data['right']}, bottom: {data['bottom']} }},"
        )
    lines.append("}")
    lines.append("")
    GENERATED.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {GENERATED}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", type=Path, default=ROOT / "mockups.zip")
    parser.add_argument("--source-dir", type=Path, default=None)
    parser.add_argument("--remove-zip", action="store_true")
    args = parser.parse_args()

    src_root = resolve_source_dir(args.zip if args.zip.exists() else None, args.source_dir)
    DEST.mkdir(parents=True, exist_ok=True)

    keep = set(PHONE_IMPORTS.keys())
    for existing in DEST.glob("*.webp"):
        if existing.name not in keep:
            existing.unlink()
            print(f"removed old frame {existing.name}")

    frames: dict[str, dict] = {}
    for dest_name, source_name in PHONE_IMPORTS.items():
        source = src_root / source_name
        if not source.is_file():
            raise SystemExit(f"missing source {source_name} in {src_root}")
        dest = DEST / dest_name
        to_output_webp(source, dest)
        measured = measure_hole(dest)
        frames[dest_name] = {
            "left": measured["left"],
            "top": measured["top"],
            "right": measured["right"],
            "bottom": measured["bottom"],
            **{k: measured[k] for k in ("width", "height", "holeWidth", "holeHeight", "pxLeft", "pxTop", "pxRight", "pxBottom")},
        }
        print(f"  {dest_name} <- {source_name}")

    (DEST / "insets.json").write_text(json.dumps(frames, indent=2) + "\n", encoding="utf-8")
    emit_generated_ts(frames)
    print(f"wrote {DEST / 'insets.json'} ({len(frames)} frames)")

    if args.remove_zip and args.zip.is_file():
        args.zip.unlink()
        print(f"removed {args.zip}")

    extract_tmp = ROOT / "tmp-mockups-extract"
    if extract_tmp.is_dir():
        shutil.rmtree(extract_tmp)
        print(f"removed {extract_tmp}")


if __name__ == "__main__":
    main()
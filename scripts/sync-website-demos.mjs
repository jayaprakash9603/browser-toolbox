#!/usr/bin/env node
/**
 * Copies the per-tool demos from the website (website/src/tool-pages/<category>/<tool>) into
 * src/app/demos/tools and writes src/app/demos/registry.generated.ts with one lazy import per tool.
 *
 * The website is a separate repository that this one git-ignores, so the copies are committed here.
 * Re-run after changing a demo on the website:  npm run sync:demos
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = resolve(ROOT, process.argv[2] ?? 'website/src/tool-pages')
const OUT = join(ROOT, 'src/app/demos/tools')
const REGISTRY = join(ROOT, 'src/app/demos/registry.generated.ts')
const MODULES = join(ROOT, 'src/modules')

const HEADER =
  '// Generated by scripts/sync-website-demos.mjs from the website tool pages. Edit the website copy and re-run.\n'

/** Website import specifiers and their extension equivalents. Anything else under `@/` fails the sync. */
const IMPORTS = {
  '@/components/tool/stage': '@/app/demos/stage',
  '@/components/tool/stage/Qr': '@/app/demos/stage/Qr',
  '@/components/tool/story': '@/app/demos/stage/types',
  '@/components/ui/Logo': '@/app/demos/stage/Logo',
  '@/config/site': '@/app/demos/stage/site',
  '@/lib/cn': '@/shared/utils/cn',
  '@/motion/gsapExtra': '@/app/demos/stage/gsap',
}

/** Story-only files that the demos never import. */
const SKIP_FILES = new Set(['Hero.tsx', 'Story.tsx', 'seo.ts'])

function fail(message) {
  console.error(`sync-website-demos: ${message}`)
  process.exit(1)
}

function walk(dir, visit) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path, visit)
    else visit(path)
  }
}

function extensionToolIds() {
  const ids = new Set()
  walk(MODULES, (path) => {
    if (!path.endsWith('registry.ts')) return
    for (const match of readFileSync(path, 'utf8').matchAll(/^\s+id: '([a-z-]+\.[a-z0-9-]+)'/gm)) ids.add(match[1])
  })
  return ids
}

function websiteDemos() {
  const registry = readFileSync(join(SOURCE, 'registry.ts'), 'utf8')
  const entries = []
  for (const match of registry.matchAll(/'([a-z-]+\.[a-z0-9-]+)':\s*\{\s*Demo: dynamic\(\(\) => import\('\.\/([^']+)\/Demo'\)\)/g))
    entries.push({ id: match[1], path: match[2] })
  if (entries.length === 0) fail(`no demos found in ${relative(ROOT, SOURCE)}/registry.ts`)
  return entries
}

function transform(source, file) {
  let text = source.replace(/^'use client'\r?\n(\r?\n)?/, '')
  text = text.replace(/from '(@\/[^']+)'/g, (whole, specifier) => {
    const mapped = IMPORTS[specifier]
    if (!mapped) fail(`${relative(ROOT, file)} imports ${specifier}, which has no extension equivalent`)
    return `from '${mapped}'`
  })
  return HEADER + text
}

function copyFile(from, to) {
  mkdirSync(dirname(to), { recursive: true })
  writeFileSync(to, transform(readFileSync(from, 'utf8'), from))
}

if (!existsSync(join(SOURCE, 'registry.ts'))) fail(`website tool pages not found at ${relative(ROOT, SOURCE)}`)

const toolIds = extensionToolIds()
const copied = []
const skipped = []
const shared = new Set()

rmSync(OUT, { recursive: true, force: true })

for (const { id, path } of websiteDemos()) {
  const dir = join(SOURCE, path)
  const demo = readFileSync(join(dir, 'Demo.tsx'), 'utf8')
  if (!toolIds.has(id)) {
    skipped.push(`${id} (not an extension tool)`)
    continue
  }
  if (!demo.includes('<DemoStage')) {
    skipped.push(`${id} (placeholder demo)`)
    continue
  }
  for (const name of readdirSync(dir)) {
    const from = join(dir, name)
    if (statSync(from).isDirectory() || SKIP_FILES.has(name) || !/\.tsx?$/.test(name)) continue
    copyFile(from, join(OUT, path, name))
    for (const match of readFileSync(from, 'utf8').matchAll(/from '\.\.\/(_[\w-]+)'/g))
      shared.add(`${dirname(path)}/${match[1]}`)
  }
  const script = readFileSync(join(dir, 'script.ts'), 'utf8')
  copied.push({ id, path, steps: /export const STEPS\b/.test(script) })
}

for (const path of shared) copyFile(join(SOURCE, `${path}.ts`), join(OUT, `${path}.ts`))

const lines = copied
  .sort((a, b) => a.id.localeCompare(b.id))
  .map(({ id, path, steps }) =>
    [
      `  '${id}': {`,
      `    demo: () => import('./tools/${path}/Demo'),`,
      steps ? `    steps: () => import('./tools/${path}/script').then((module) => module.STEPS),` : null,
      '  },',
    ]
      .filter(Boolean)
      .join('\n'),
  )

writeFileSync(
  REGISTRY,
  `${HEADER}import type { ComponentType } from 'react'

import type { WalkStep } from './stage/types'

export interface DemoEntry {
  demo: () => Promise<{ default: ComponentType }>
  steps?: () => Promise<readonly WalkStep[]>
}

/** Tool id to its website demo. Literal imports so every demo is its own chunk. */
export const DEMOS: Record<string, DemoEntry> = {
${lines.join('\n')}
}
`,
)

console.log(`sync-website-demos: ${copied.length} demos copied to ${relative(ROOT, OUT)}`)
if (shared.size) console.log(`  shared helpers: ${[...shared].join(', ')}`)
if (skipped.length) console.log(`  skipped: ${skipped.join('; ')}`)
const missing = [...toolIds].filter((id) => !copied.some((entry) => entry.id === id))
if (missing.length) console.log(`  tools without a demo (poster fallback): ${missing.join(', ')}`)

/**
 * Regenerate catalog-mockups.generated.ts from mockups DEVICE_FILE + public/simulator/frames/insets.json
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const insetPath = resolve(root, 'public/simulator/frames/insets.json')
const mockupsPath = resolve(root, 'src/tools/design/responsive-viewer/mockups.ts')
const outPath = resolve(root, 'src/tools/design/responsive-viewer/catalog-mockups.generated.ts')

const insets = JSON.parse(readFileSync(insetPath, 'utf8'))
const mockupsSrc = readFileSync(mockupsPath, 'utf8')
const deviceBlock = mockupsSrc.match(/const DEVICE_FILE[^=]*=\s*\{([^}]+)\}/s)
if (!deviceBlock) {
  console.error('DEVICE_FILE block not found in mockups.ts')
  process.exit(1)
}

const pairs = [...deviceBlock[1].matchAll(/'([^']+)':\s*'([^']+)'/g)]
const lines = [
  '/** Generated by scripts/build-simulator-frames.mjs — do not edit by hand. */',
  '/** Tuple: frame file, left, top, right, bottom (MIT open-device-frame). */',
  '',
  'export type CatalogMockup = readonly [string, number, number, number, number]',
  '',
  'export const CATALOG_MOCKUPS: Record<string, CatalogMockup> = {',
]

let count = 0
for (const [, deviceId, frameFile] of pairs) {
  const meta = insets[frameFile]
  if (!meta) {
    console.warn(`skip ${deviceId}: no insets for ${frameFile}`)
    continue
  }
  lines.push(
    `  ${JSON.stringify(deviceId)}: [${JSON.stringify(frameFile)}, ${meta.left}, ${meta.top}, ${meta.right}, ${meta.bottom}],`,
  )
  count++
}

lines.push('}', '')

writeFileSync(outPath, lines.join('\n'), 'utf8')
console.log(`[simulator-frames] wrote ${outPath} (${count} devices)`)
function flattenRules() {
  const out: Record<string, string> = {}
  for (const [id, copy] of Object.entries(RULE_COPY) as [A11yRuleId, { title: string; fix: string }][]) {
    out[`a11y.rule.${id}.title`] = copy.title
    out[`a11y.rule.${id}.fix`] = copy.fix
  }
  return out
}


import type { YoutubeFeatureDef, YoutubeSection } from './types'

function toggles(
  section: YoutubeSection,
  ids: string[],
  opts?: Partial<Pick<YoutubeFeatureDef, 'impl' | 'default' | 'bestEffort' | 'thirdParty'>>,
): YoutubeFeatureDef[] {
  const impl = opts?.impl ?? 'css'
  const defaultVal = opts?.default ?? false
  return ids.map((id) => ({
    id,
    section,
    kind: 'toggle',
    impl,
    default: defaultVal,
    ...(opts?.bestEffort ? { bestEffort: true } : {}),
    ...(opts?.thirdParty ? { thirdParty: true } : {}),
  }))
}

